def get_suggestions(query: str, limit: int = 7) -> list[dict]:
    if not query or len(query.strip()) < 2:
        return []

    words = [w for w in query.lower().split() if len(w) > 1]
    q = query.lower().strip()

    scored = []
    for s in SUGGESTIONS:
        sl = s["text"].lower()
        if q in sl:
            # точное вхождение запроса как подстроки
            scored.append((s, 3))
        elif words and all(w in sl for w in words):
            # все слова запроса есть в подсказке
            scored.append((s, 2))
        elif words and any(w in sl for w in words if len(w) >= 3):
            # хотя бы одно значимое слово совпадает
            scored.append((s, 1))

    scored.sort(key=lambda x: -x[1])
    top = [s for s, _ in scored[:limit]]

    grouped: list[dict] = []
    seen: dict[str, dict] = {}
    for item in top:
        cat = item["category"]
        if cat not in seen:
            seen[cat] = {"category": cat, "items": []}
            grouped.append(seen[cat])
        seen[cat]["items"].append(item["text"])

    return grouped
